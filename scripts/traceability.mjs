import { readFile, readdir, writeFile } from "node:fs/promises";
import { join, relative } from "node:path";
import ts from "typescript";

const root = "src";
const rulesText = await readFile("docs/rules.md", "utf8");
const rules = [...rulesText.matchAll(/^\| ([A-Z][A-Z0-9]*-\d+) \|.*?`([A-Z][A-Z0-9]*_\d+)`/gm)]
  .map((match) => ({ id: match[1], testId: match[2] }));
const testsByRule = new Map(rules.map(({ id }) => [id, []]));

function ruleIds(title) {
  return [...title.matchAll(/\b([A-Z][A-Z0-9]*_\d+)\b/g)].map((match) => match[1].replace("_", "-"));
}

function callName(node) {
  return ts.isCallExpression(node) && ts.isIdentifier(node.expression) ? node.expression.text : "";
}

function countExpects(node) {
  let count = 0;
  function visit(current) {
    if (callName(current) === "expect") count += 1;
    ts.forEachChild(current, visit);
  }
  visit(node);
  return count;
}

async function visit(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) await visit(path);
    else if (/\.(test|spec)\.tsx?$/.test(entry.name)) {
      const text = await readFile(path, "utf8");
      const source = ts.createSourceFile(path, text, ts.ScriptTarget.Latest, true);
      function scan(node, groups = []) {
        const name = callName(node);
        const titleNode = name && ["describe", "it", "test"].includes(name) ? node.arguments[0] : undefined;
        const title = titleNode && (ts.isStringLiteral(titleNode) || ts.isNoSubstitutionTemplateLiteral(titleNode)) ? titleNode.text : undefined;
        if (name === "describe") {
          const nested = title ? [...groups, title] : groups;
          for (const child of node.arguments.slice(1)) scan(child, nested);
          return;
        }
        if (["it", "test"].includes(name) && title) {
          const ids = [...new Set([...groups.flatMap(ruleIds), ...ruleIds(title)])];
          const body = node.arguments[1];
          const expects = body ? countExpects(body) : 0;
          for (const testId of ids) {
            const rule = rules.find((item) => item.id === testId);
            if (rule) testsByRule.get(rule.id)?.push({ file: relative(".", path).replaceAll("\\", "/"), title, expects, ids });
          }
          return;
        }
        ts.forEachChild(node, (child) => scan(child, groups));
      }
      scan(source);
    }
  }
}

await visit(root);
const flagged = [];
const lines = ["# Rule traceability", "", "Generated by `npm run traceability`.", "", "| Mã | Test (file · tên) | Số expect | Cờ |", "|---|---|---:|---|"];
for (const rule of rules) {
  const tests = testsByRule.get(rule.id) ?? [];
  const onlyShared = tests.length > 0 && tests.every((test) => test.ids.length >= 3);
  if (onlyShared) flagged.push(rule.id);
  const testNames = tests.length ? tests.map((test) => `${test.file} · ${test.title}`).join("<br>") : "—";
  const counts = tests.length ? tests.map((test) => String(test.expects)).join("<br>") : "—";
  lines.push(`| ${rule.id} | ${testNames} | ${counts} | ${onlyShared ? "CHỈ TEST CHUNG" : ""} |`);
}
lines.push("", "## Mã chỉ được kiểm trong test chung", "", flagged.length ? flagged.map((id) => `- ${id}`).join("\n") : "Không có mã bị cờ.", "");
await writeFile("docs/traceability.md", lines.join("\n"), "utf8");
console.log(`Generated docs/traceability.md (${rules.length} rules; ${flagged.length} flagged).`);
